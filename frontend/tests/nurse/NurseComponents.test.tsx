import { render, screen, fireEvent } from '@testing-library/react';
import { describe, it, expect, vi } from 'vitest';
import { ConfirmedPanel } from '../../src/features/nurse/components/ConfirmedPanel';
import { AlertsPanel } from '../../src/features/nurse/components/AlertsPanel';
import { QuestionPicker } from '../../src/features/nurse/components/QuestionPicker';
import { SemanticFrame, TriageSummary, Alert } from '../../src/types';

const mockFrame: SemanticFrame = {
  schema_version: '1.0',
  session_id: 'test-session',
  modality: ['touch'],
  chief_complaint: { code: 'PAIN', label_vi: 'Đau ngực', free_text: null },
  pain: {
    present: true,
    severity: 7,
    body_regions: ['CHEST'],
    onset: { value: 2, unit: 'hour' },
  },
  allergy: {
    has_allergy: true,
    items: [{ category: 'drug', name: 'Penicillin' }],
  },
  extra_symptoms: [],
  uncertain_fields: [],
  field_confidence: {},
  conflicts: [],
  missing_fields: [],
};

const mockSummary: TriageSummary = {
  session_id: 'test-session',
  intake_code: 'AC-0042',
  queue_number: null,
  status: 'summary_ready',
  frame: mockFrame,
  nl_text_vi: 'Bạn bị đau ở ngực, mức 7/10, bắt đầu cách đây 2 giờ.',
  nl_source: 'llm',
  fallback_reason: null,
  validator: { passed: true, violations: [] },
  alerts: [],
  nurse_view: {
    confirmed: [{ label_vi: 'Lý do khám', detail: 'Đau ngực' }],
    needs_attention: [],
  },
  flags: { interpreter_requested: false, emergency_flag: false },
  timestamps: { created: '2026-11-07T00:00:00Z' },
};

describe('ConfirmedPanel', () => {
  it('renders gray editing status when patient has not confirmed', () => {
    render(<ConfirmedPanel status="collecting" frame={mockFrame} summary={null} />);
    expect(screen.getByText('Bệnh nhân đang nhập thông tin...')).toBeInTheDocument();
    expect(screen.getByTestId('confirmed-panel')).toHaveClass('bg-canvas/60');
  });

  it('renders green confirmed status when patient has confirmed', () => {
    render(
      <ConfirmedPanel
        status="patient_confirmed"
        frame={mockFrame}
        summary={mockSummary}
      />
    );
    expect(screen.getByText('Đã xác nhận từ bệnh nhân')).toBeInTheDocument();
    expect(screen.getByTestId('confirmed-panel')).toHaveClass('bg-status-success/5');
    expect(screen.getByText(/Penicillin/)).toBeInTheDocument();
    expect(screen.getByText(/CHEST/)).toBeInTheDocument();
  });

  it('displays LLM source badge when generated by LLM', () => {
    render(
      <ConfirmedPanel
        status="patient_confirmed"
        frame={mockFrame}
        summary={mockSummary}
      />
    );
    const badge = screen.getByTestId('summary-source-badge');
    expect(badge).toHaveTextContent('Nguồn: LLM');
  });

  it('displays Fallback template badge when generated by fallback', () => {
    const fallbackSummary: TriageSummary = {
      ...mockSummary,
      nl_source: 'fallback_template',
      fallback_reason: 'timeout',
    };
    render(
      <ConfirmedPanel
        status="patient_confirmed"
        frame={mockFrame}
        summary={fallbackSummary}
      />
    );
    const badge = screen.getByTestId('summary-source-badge');
    expect(badge).toHaveTextContent('Nguồn: Mẫu cố định (Dự phòng)');
  });
});

describe('AlertsPanel', () => {
  const alerts: Alert[] = [
    {
      code: 'RED_FLAG_CHEST_PAIN',
      level: 'critical',
      message_vi: 'Cơn đau ngực dữ dội nghi ngờ khẩn cấp.',
      needs_nurse_ack: true,
    },
    {
      code: 'MISSING_ALLERGY',
      level: 'warning',
      message_vi: 'Chưa khai báo dị ứng.',
      needs_nurse_ack: true,
    },
  ];

  it('renders alerts and highlights critical items', () => {
    render(
      <AlertsPanel
        alerts={alerts}
        acknowledgedAlerts={new Set()}
        onAcknowledgeAlert={() => {}}
        audioAlertEnabled={false}
      />
    );
    expect(screen.getByText('Cần hỏi lại & Dị ứng')).toBeInTheDocument();
    expect(screen.getByText('KHẨN')).toBeInTheDocument();
    expect(screen.getByText('Cơn đau ngực dữ dội nghi ngờ khẩn cấp.')).toBeInTheDocument();
  });

  it('calls onAcknowledgeAlert when acknowledge button is clicked', () => {
    const handleAck = vi.fn();
    render(
      <AlertsPanel
        alerts={alerts}
        acknowledgedAlerts={new Set()}
        onAcknowledgeAlert={handleAck}
        audioAlertEnabled={false}
      />
    );
    const ackBtns = screen.getAllByRole('button', { name: /Xác nhận đã biết cảnh báo/i });
    fireEvent.click(ackBtns[0]);
    expect(handleAck).toHaveBeenCalledWith('RED_FLAG_CHEST_PAIN');
  });

  it('shows acknowledged status when alert is in acknowledged set', () => {
    render(
      <AlertsPanel
        alerts={alerts}
        acknowledgedAlerts={new Set(['RED_FLAG_CHEST_PAIN'])}
        onAcknowledgeAlert={() => {}}
        audioAlertEnabled={false}
      />
    );
    expect(screen.getByText('Đã xử lý')).toBeInTheDocument();
  });
});

describe('QuestionPicker', () => {
  it('renders question buttons and triggers send on click', () => {
    const handleSend = vi.fn();
    render(<QuestionPicker onSendQuestion={handleSend} />);

    expect(screen.getByTestId('btn-question-ASK_DRUG_ALLERGY')).toBeInTheDocument();
    expect(screen.getByTestId('btn-question-ASK_PAIN_DURATION')).toBeInTheDocument();
    expect(screen.getByTestId('btn-question-ASK_FEVER')).toBeInTheDocument();

    fireEvent.click(screen.getByTestId('btn-question-ASK_DRUG_ALLERGY'));
    expect(handleSend).toHaveBeenCalledWith(
      expect.objectContaining({
        templateCode: 'ASK_DRUG_ALLERGY',
        textVi: 'Bạn có dị ứng thuốc nào không?',
      })
    );
  });
});
